'use strict';
// Exercise the live diagnostics facade together with the real controller.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const Controller = require('../../assets/js/spotify-playback-controller.js');
const {Clock, SpotifySimulator} = require('./simulator.js');
const html = fs.readFileSync('FretFlow.html','utf8');
const source = html.slice(html.indexOf('// Opt-in, memory-only playback diagnostics.'), html.indexOf('class SpotifyPractice'));
const context = {window:{}, Date}; vm.createContext(context);
vm.runInContext(source+'\nwindow.recorder = SpotifyPracticeDiagnostics;', context);
const facade = context.window.FretFlowSpotifyDiagnostics, recorder = context.window.recorder;
const clock = new Clock(), api = new SpotifySimulator(clock);
api.change({trackId:'PrivateTrack', deviceId:'PrivateDevice', playing:true, positionMs:10000});
const controller = new Controller({api, clock, timeoutMs:1000, verifyIntervalMs:100, toleranceMs:100});
controller.selectContext({contextId:'PrivateTab',trackId:'PrivateTrack',trackUri:'spotify:track:PrivateTrack',durationMs:120000});
recorder.attach(controller);
const intent = () => controller.requestPlayback({contextId:'PrivateTab',trackId:'PrivateTrack',trackUri:'spotify:track:PrivateTrack',playing:true,position:{mode:'absolute',ms:30000},reason:'replay'});
(async()=>{
  intent(); await clock.advance(20); assert.equal(facade.report(),'');
  facade.enable(); intent(); await clock.advance(20);
  const report = facade.report(); assert.match(report,/"type":"intent"/); assert.match(report,/"type":"dispatch"/); assert.match(report,/"type":"reconciled"/);
  assert.doesNotMatch(report,/PrivateTrack|PrivateDevice|PrivateTab|spotify:track/);
  assert.deepEqual(api.commands.map(c=>c.name),['seek','seek']);
  facade.disable(); const stopped=facade.report(); intent(); await clock.advance(20); assert.equal(facade.report(),stopped);
  facade.enable(); for(let i=0;i<300;i++) recorder.record('test',{positionMs:i});
  assert.equal(facade.report().split('\n').filter(line=>JSON.parse(line).action === 'test').length,250);
  facade.clear(); assert.equal(facade.report(),''); facade.disable();
  console.log('Spotify diagnostics: 5 privacy and lifecycle checks passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
